package BasicsOfJava;

public class IncrementDecrementOperator {
    public static void main(String[] args) {
        int x = 10;
        int y = 20;
        System.out.println(x);
        x++; // OR x = x + 1. Increment
        System.out.println(x);
        x--; // OR x = x - 1. Decrement
        System.out.println(x); /* If i have to comment out the whole paragraph the use This Amazing Format bro!! */
        System.out.println(y);
        --y;
        System.out.println(y);
        ++y;
        System.out.println(y);
        /* Now (++x) means pehle inc then do print
        For (x++) means use x and then increment
         */

    }
}
