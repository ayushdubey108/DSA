package BasicsOfJava;

public class ArithmeticOperation {
    public static void main(String[] args) {
        int x = 8;
        int y = 4;
        System.out.println(x+y);
        System.out.println(x-y);
        System.out.println(y-x);
        System.out.println(x*y);
        System.out.println(x/y);
    }
}
