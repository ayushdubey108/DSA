package BasicsOfJava;

public class PercentageOf5Subjects {
    public static void main(String[] args) {
        double x1, x2, x3, x4, x5;
        x1 = 90;
        x2 = 91;
        x3 = 94;
        x4 = 95;
        x5 = 96;
        double sum = (x1+x2+x3+x4+x5)/5;
        System.out.println("The Percentage of above given 5 subjects are : "+sum); // Again remember this (+sum) format to print numbers
    }
}
