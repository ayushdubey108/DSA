package Leetcode;

import java.util.Scanner;

public class Q14 {
    public static void main(String[] args) {
        Scanner sc = new Scanner(System.in);
        int t = sc.nextInt();
        while(t-- > 0){
            int k = sc.nextInt();
            if(k > 0){
                System.out.println("HARD");
            }
            else{
                System.out.println("EASY");
            }
        }

    }
}
